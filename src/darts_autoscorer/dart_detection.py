import cv2
import numpy as np


class DartDetector:
    """
    Detect changed image regions between two board frames.
    """

    def __init__(self, board_center, threshold=16, min_area=400, max_shift=1, frame_patience=3, warmup_frames=30,
                openKernel_size=3, closeKernel_size=7):
        """
        board_center: tuple[int, int]
            Coordinates of the dartboard centre in the rectified image.
        threshold: int, optional
            MOG2 threshold used to distinguish foreground from background.
        min_area: int, optional
            Minimum contour area required to consider a region a candidate dart.
        max_shift: int, optional
            Maximum allowed displacement (in pixels) of bounding box edges
            between consecutive frames to consider a candidate stable.
        frame_patience: int, optional
            Number of consecutive stable frames required to capture a dart.
        warmup_frames: int, optional
            Number of initial frames used to train the MOG2 background model.
        openKernel_size: int, optional
            Size of the morphological opening kernel used to remove noise.
        closeKernel_size: int, optional
            Size of the morphological closing kernel used to fill holes and
            connect nearby foreground regions.
        """

        self.board_center = board_center

        self.threshold = threshold
        self.min_area = min_area
        self.max_shift = max_shift

        self.n_frames = 0
        self.stable_frames = 0

        # Frames a dart must remain still before scoring
        self.frame_patience = frame_patience

        # Warm-up frames are used for pre-training MOG2 gaussian model.
        # 30 -> ~1 second at 30 fps /ensure the board stays empty during this window!)
        self.warmup_frames = warmup_frames  

        # Kernels used to clean noise (open) and then close dart shilouette (close)
        self.open_kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (openKernel_size, openKernel_size))
        self.close_kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (closeKernel_size, closeKernel_size))

        self.settled_mask = None # Contains all previously detected darts as white pixels

        self.prev_bbox = None

        self.MOG2_subtractor = cv2.createBackgroundSubtractorMOG2(history=500, varThreshold=self.threshold, detectShadows=True)


    def detect(self, current_frame):
        """
        Detect new darts using MOG2 background subtraction and temporal tracking.

        The foreground mask is processed using morphological operations to remove
        noise and improve dart silhouettes. Previously captured darts are removed
        using a settled mask. Candidate regions are identified through contour
        detection and tracked across consecutive frames until they remain stable
        for the specified number of frames.

        Once a dart is considered settled, its tip is estimated using PCA and
        its silhouette is stored to prevent subsequent detections.

        Parameters
        ----------
        current_frame: np.ndarray
            Current rectified BGR frame of the dartboard.

        Returns
        -------
        foreground_mask: np.ndarray
            Binary foreground mask generated by MOG2.
        new_dart_mask: np.ndarray
            Binary mask containing foreground regions not previously captured.
        boxes: list[tuple[int, int, int, int]]
            Bounding boxes (x, y, width, height) of candidate dart regions.
        tip: tuple[int, int] or None
            Estimated dart tip coordinates if a new dart has been captured;
            otherwise, None.
        """

        # Increment readed frames
        self.n_frames += 1

        # In the first call, set the "settled_mask" to full black
        if self.settled_mask is None:
            self.settled_mask = np.zeros(current_frame.shape[:2], dtype=np.uint8)   

        # Obtain the mask cotaining the foreground in white using MOG2 algorithm
        foreground_mask = self.MOG2_subtractor.apply(current_frame)
        _, foreground_mask = cv2.threshold(foreground_mask, 200, 255, cv2.THRESH_BINARY)

        # Initialize variables
        new_dart_mask = np.zeros_like(foreground_mask)
        tip = None
        boxes = []

        # Only if the warmup frames have been proceessed, proceed with the detection of darts
        if self.n_frames >= self.warmup_frames and self.settled_mask is not None:

            # Remove small foreground regions (noise) and then fill small holes and connect nearby foreground regions
            foreground_mask = cv2.morphologyEx(foreground_mask, cv2.MORPH_OPEN, self.open_kernel)
            foreground_mask = cv2.morphologyEx(foreground_mask, cv2.MORPH_CLOSE, self.close_kernel)

            # Remove already-captured darts from the foreground pixes 
            self.settled_mask = cv2.bitwise_and(self.settled_mask, foreground_mask)

            # Contains foregorund pixes (potential darts) that are NOT in settled_mask
            new_dart_mask = cv2.bitwise_and(foreground_mask, cv2.bitwise_not(self.settled_mask)) 

            # Find contours only in the "new_dart_mask"
            contours, _ = cv2.findContours(new_dart_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
            boxes = [cv2.boundingRect(c) for c in contours if cv2.contourArea(c) >= self.min_area]

            # If there are potential darts
            if boxes:

                # Track the largest candidate bounding box across frames
                curr_bbox = max(boxes, key=lambda b: b[2] * b[3])

                # Check weather the bounding box matches with the previous bounding box
                if self.prev_bbox is not None and self._is_same_box(curr_bbox, self.prev_bbox):
                    self.stable_frames += 1
                else:
                    self.stable_frames = 0

                self.prev_bbox = curr_bbox

                # If a large bounding box has persist enough in a stream of frames -> New Dart
                if self.stable_frames >= self.frame_patience:

                    # Detect tip coordinates
                    tip = self._locate_tip(new_dart_mask, curr_bbox, self.board_center)

                    # Stamp detect dart into settled_mask so next frame ignores this dart completely
                    self.settled_mask = cv2.bitwise_or(self.settled_mask, new_dart_mask)
                    self.stable_frames = 0
                    self.prev_bbox = None

        return foreground_mask, new_dart_mask, boxes, tip


    def _is_same_box(self, box_a, box_b):
        """
        Returns True if all 4 edges of two (x, y, w, h) boxes moved by <= max_shift pixels.
        """

        ax1, ay1, aw, ah = box_a
        bx1, by1, bw, bh = box_b
        ax2, ay2 = ax1 + aw, ay1 + ah
        bx2, by2 = bx1 + bw, by1 + bh

        return (
            abs(ax1 - bx1) <= self.max_shift
            and abs(ay1 - by1) <= self.max_shift
            and abs(ax2 - bx2) <= self.max_shift
            and abs(ay2 - by2) <= self.max_shift
        )


    def _locate_tip(self, mask, bbox, board_center):
        """
        Estimate the dart tip using PCA.

        Parameters
        ----------
        mask : np.ndarray
            Binary difference mask returned by detect().
        bbox : tuple
            Single bounding box (x, y, width, height) returnned by detect().
        board_center : tuple
            Centre of the rectified dartboard.

        Returns
        -------
        tuple[int, int] or None
            Estimated tip coordinates in the full image.
        """

        x, y, w, h = bbox

        # Extract the dart region.
        roi = mask[y:y+h, x:x+w]

        # Find the contour.
        contours, _ = cv2.findContours(
            roi,
            cv2.RETR_EXTERNAL,
            cv2.CHAIN_APPROX_NONE,
        )

        if not contours:
            return None

        # Pick the contour with the biggest area
        contour = max(contours, key=cv2.contourArea)

        # Reshape from (N,1,2) (given by OpenCV) to (N,2) -> [[x,y]] of contour points
        points = contour.reshape(-1, 2).astype(np.float32)

        # At least we need 3 points to perform a meaningfully PCA
        if len(points) < 3:
            return None

        # Calculate the principal axis using PCA.
        mean, eigenvectors = cv2.PCACompute(points, mean=None)

        # Project points onto the principal axis.
        axis = eigenvectors[0] # Principal axis (where the dart tip is located)
        projections = (points - mean) @ axis

        # Find the two extreme points.
        point_a = points[np.argmin(projections)]
        point_b = points[np.argmax(projections)]

        # Convert ROI coordinates to full-image coordinates.
        point_a += np.array([x, y])
        point_b += np.array([x, y])

        # Select the endpoint closest to the board centre.
        board_center = np.array(board_center)

        dist_a = np.linalg.norm(point_a - board_center)
        dist_b = np.linalg.norm(point_b - board_center)

        tip = point_a if dist_a < dist_b else point_b

        return tuple(np.round(tip).astype(int))

